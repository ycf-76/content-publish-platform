// Fibonacci 球面均匀分布：黄金角螺旋，避免聚集/空洞
function buildSphere(n: number) {
  const points: { x: number; y: number; z: number }[] = []
  const goldenAngle = Math.PI * (3 - Math.sqrt(5))
  for (let i = 0; i < n; i++) {
    const y = 1 - (i / (n - 1)) * 2  // y 从 1 到 -1
    const r = Math.sqrt(1 - y * y)
    const theta = goldenAngle * i
    points.push({
      x: Math.cos(theta) * r,
      y,
      z: Math.sin(theta) * r,
    })
  }
  return points
}

function tick() {
  // 自动绕 Y 轴旋转
  targetRotY += AUTO_ROTATE_SPEED

  if (hovering) {
    // 鼠标左右位置 → Y 轴旋转方向与速度（左半边反转，右半边加速）
    targetRotY += mouseNX * 0.015
    // 鼠标上下位置 → X 轴倾斜角度
    targetRotX = mouseNY * 0.35
  }

  // 缓动逼近目标角度，避免生硬
  rotY += (targetRotY - rotY) * 0.06
  rotX += (targetRotX - rotX) * 0.06

  const cosY = Math.cos(rotY)
  const sinY = Math.sin(rotY)
  const cosX = Math.cos(rotX)
  const sinX = Math.sin(rotX)

  for (const item of items.value) {
    // 先绕 Y 轴
    const x1 = item.bx * cosY - item.bz * sinY
    const z1 = item.bx * sinY + item.bz * cosY
    // 再绕 X 轴
    const y1 = item.by * cosX - z1 * sinX
    const z2 = item.by * sinX + z1 * cosX

    // 深度透视：z 归一化到 0~1，决定 scale 与 opacity
    const depth = (z2 + 1) / 2  // 0(远) ~ 1(近)
    item.scale = 0.45 + depth * (1.3 - 0.45)   // 0.45 ~ 1.3
    item.opacity = 0.25 + depth * (1.0 - 0.25) // 0.25 ~ 1.0
    item.x = x1 * RADIUS
    item.y = y1 * RADIUS
    item.zIndex = Math.round(depth * 1000)
  }

  rafId = requestAnimationFrame(tick)
}

