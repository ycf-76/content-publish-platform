  // 归一化到 -1 ~ 1
  mouseNX = ((e.clientX - rect.left) / rect.width) * 2 - 1
  mouseNY = ((e.clientY - rect.top) / rect.height) * 2 - 1
  hovering = true
}

function onMouseLeave() {
  hovering = false
  // 鼠标离开后缓慢回正 X 轴倾斜
  targetRotX = 0
}

onMounted(() => {
  const sphere = buildSphere(TARGET_COUNT)
  items.value = sphere.map((p, i) => {
    const icon = SOCIAL_ICONS[i % SOCIAL_ICONS.length]
    return {
      bx: p.x, by: p.y, bz: p.z,
      x: 0, y: 0, scale: 1, opacity: 1, zIndex: 0,
      color: icon.color, svg: icon.svg,
    }
  })
  tick()
})

onUnmounted(() => {
  cancelAnimationFrame(rafId)
})
</script>

